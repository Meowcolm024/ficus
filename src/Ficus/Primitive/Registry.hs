builtinTraits :: [BuiltinType]
builtinTraits = [ExceptionBuiltin]

builtinTypeName :: BuiltinType -> Text
builtinTypeName builtin = case builtin of
  HandleBuiltin -> "Handle"
  ByteBuiltin -> "Byte"
  VecBuiltin -> "Vec"
  RefBuiltin -> "Ref"
  ExceptionBuiltin -> "Exception"
  IOModeBuiltin -> "IOMode"

builtinTypeKey :: BuiltinType -> Text
builtinTypeKey builtin = case builtin of
  HandleBuiltin -> "HANDLE"
  ByteBuiltin -> "BYTE"
  VecBuiltin -> "VEC"
  RefBuiltin -> "REF"
  ExceptionBuiltin -> "EXCEPTION"
  IOModeBuiltin -> "IO_MODE"

builtinTypeArity :: BuiltinType -> Int
builtinTypeArity builtin = case builtin of
  VecBuiltin -> 1
  RefBuiltin -> 1
  ExceptionBuiltin -> 1
  _ -> 0

