-- | Stage-neutral primitive inventory. Source keys, operation identities,
-- type templates and operand counts live here; no AST or evaluator is imported.
module Ficus.Primitive.Registry where

import Data.List (elemIndex)
import Data.Text (Text)

data Intrinsic = IntType | FloatType | BoolType | CharType | StringType | UnitType | ListType | ProductType | FunctionType | TypeKind | TrueConstructor | FalseConstructor | ConsConstructor | NilConstructor deriving (Eq, Ord, Show)

-- Reserved source spellings are metadata; Name builds their ordinary identities.
intrinsicTypes :: [(Text, Intrinsic)]
intrinsicTypes = [("Int", IntType), ("Float", FloatType), ("Bool", BoolType), ("Char", CharType), ("String", StringType), ("Unit", UnitType), ("[]", ListType), ("(*)", ProductType), ("(->)", FunctionType)]

intrinsicConstructors :: [(Text, Intrinsic)]
intrinsicConstructors = [("True", TrueConstructor), ("False", FalseConstructor), ("::", ConsConstructor), ("[]", NilConstructor)]

intrinsicKinds :: [(Text, Intrinsic)]
intrinsicKinds = [("Type", TypeKind)]

intrinsicArity :: Intrinsic -> Int
intrinsicArity intrinsic = case intrinsic of
  ListType -> 1
  ProductType -> 2
  FunctionType -> 2
  _ -> 0

data Primitive nominal
  = IntAdd
  | IntSubtract
  | IntMultiply
  | IntDivide
  | IntRemainder
  | IntEqual
  | IntLess
  | IntShow
  | StringAppend
  | StringEqual
  | StringLength
  | IntToFloat
  | FloatAdd
  | FloatSubtract
  | FloatMultiply
  | FloatDivide
  | FloatEqual
  | FloatLess
  | FloatShow
  | FloatToInt
  | CharEqual
  | CharLess
  | CharShow
  | StringLess
  | StringToChars
  | CharsToString
  | HandleStdin nominal
  | HandleStdout nominal
  | HandleStderr nominal
  | HandleRead nominal
  | HandleWrite nominal
  | VecFromList nominal
  | VecToList nominal
  | VecLength nominal
  | ByteFromInt nominal
  | ByteToInt nominal
  | IntNegate
  | FloatNegate
  deriving (Eq, Ord, Show, Functor, Foldable, Traversable)

-- Opaque library constructors remain nominal in Core and are erased at Runtime.
data BuiltinType = HandleBuiltin | ByteBuiltin | VecBuiltin deriving (Eq, Ord, Show)

builtinTypes :: [BuiltinType]
builtinTypes = [HandleBuiltin, ByteBuiltin, VecBuiltin]

builtinTypeName :: BuiltinType -> Text
builtinTypeName builtin = case builtin of
  HandleBuiltin -> "Handle"
  ByteBuiltin -> "Byte"
  VecBuiltin -> "Vec"

builtinTypeKey :: BuiltinType -> Text
builtinTypeKey builtin = case builtin of
  HandleBuiltin -> "HANDLE"
  ByteBuiltin -> "BYTE"
  VecBuiltin -> "VEC"

builtinTypeArity :: BuiltinType -> Int
builtinTypeArity builtin = case builtin of
  VecBuiltin -> 1
  _ -> 0

