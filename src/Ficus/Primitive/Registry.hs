allPrimitives :: [Primitive ()]
allPrimitives = map (erasePrimitive . snd) primitiveCatalog

erasePrimitive :: Primitive nominal -> Primitive ()
erasePrimitive = fmap (const ())

primitiveIndex :: Primitive nominal -> Maybe Int
primitiveIndex operation = elemIndex (erasePrimitive operation) allPrimitives

-- Templates are saturated semantic contracts, independent of inference/Core.
data PrimitiveType nominal
  = ScalarType Intrinsic
  | ListTypeOf (PrimitiveType nominal)
  | NominalType nominal [PrimitiveType nominal]
  | TypeParameter
  deriving (Eq, Show, Functor, Foldable, Traversable)

primitiveSignature :: Primitive nominal -> ([PrimitiveType nominal], PrimitiveType nominal)
primitiveSignature primitiveId = case primitiveId of
  IntAdd -> intBinary int
  IntSubtract -> intBinary int
  IntMultiply -> intBinary int
  IntDivide -> intBinary int
  IntRemainder -> intBinary int
  IntEqual -> intBinary bool
  IntLess -> intBinary bool
  IntShow -> ([int], string)
  StringAppend -> ([string, string], string)
  StringEqual -> ([string, string], bool)
  StringLength -> ([string], int)
  IntToFloat -> ([int], float)
  FloatAdd -> floatBinary float
  FloatSubtract -> floatBinary float
  FloatMultiply -> floatBinary float
  FloatDivide -> floatBinary float
  FloatEqual -> floatBinary bool
  FloatLess -> floatBinary bool
  FloatShow -> ([float], string)
  FloatToInt -> ([float], int)
  CharEqual -> ([char, char], bool)
  CharLess -> ([char, char], bool)
  CharShow -> ([char], string)
  StringLess -> ([string, string], bool)
  StringToChars -> ([string], ListTypeOf char)
  CharsToString -> ([ListTypeOf char], string)
  HandleStdin ident -> ([], NominalType ident [])
  HandleStdout ident -> ([], NominalType ident [])
  HandleStderr ident -> ([], NominalType ident [])
  HandleRead ident -> ([NominalType ident [], int], string)
  HandleWrite ident -> ([NominalType ident [], string], ScalarType UnitType)
  VecFromList ident -> ([ListTypeOf a], vec ident a)
  VecToList ident -> ([vec ident a], ListTypeOf a)
  VecLength ident -> ([vec ident a], int)
  ByteFromInt ident -> ([int], NominalType ident [])
  ByteToInt ident -> ([NominalType ident []], int)
  IntNegate -> ([int], int)
  FloatNegate -> ([ScalarType FloatType], ScalarType FloatType)
  where
    int = ScalarType IntType
    bool = ScalarType BoolType
    string = ScalarType StringType
    float = ScalarType FloatType
    char = ScalarType CharType
    a = TypeParameter
    vec ident argument = NominalType ident [argument]
    floatBinary result = ([float, float], result)
    intBinary result = ([int, int], result)

primitiveArity :: Primitive nominal -> Int
primitiveArity = length . fst . primitiveSignature
