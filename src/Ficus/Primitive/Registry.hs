data Intrinsic = IntType | FloatType | BoolType | CharType | StringType | UnitType | ListType | ProductType | FunctionType | LazyFunctionType | TypeKind | TrueConstructor | FalseConstructor | ConsConstructor | NilConstructor deriving (Eq, Ord, Show)

-- Reserved source spellings are metadata; Name builds their ordinary identities.
intrinsicTypes :: [(Text, Intrinsic)]
intrinsicTypes = [("Int", IntType), ("Float", FloatType), ("Bool", BoolType), ("Char", CharType), ("String", StringType), ("Unit", UnitType), ("[]", ListType), ("(*)", ProductType), ("(->)", FunctionType), ("(~>)", LazyFunctionType)]

intrinsicConstructors :: [(Text, Intrinsic)]
intrinsicConstructors = [("True", TrueConstructor), ("False", FalseConstructor), ("::", ConsConstructor), ("[]", NilConstructor)]

intrinsicKinds :: [(Text, Intrinsic)]
intrinsicKinds = [("Type", TypeKind)]

intrinsicArity :: Intrinsic -> Int
intrinsicArity intrinsic = case intrinsic of
  ListType -> 1
  ProductType -> 2
  FunctionType -> 2
  LazyFunctionType -> 2
  _ -> 0

data Primitive nominal
  = IntAdd
  | IntSubtract
  | IntMultiply
  | IntDivide
  | IntRemainder
  | IntEqual
  | IntLess
  | IntShow
  | StringAppend
  | StringEqual
  | StringLength
  | IntToFloat
  | FloatAdd
  | FloatSubtract
  | FloatMultiply
  | FloatDivide
  | FloatEqual
  | FloatLess
  | FloatShow
  | FloatToInt
  | CharEqual
  | CharLess
  | CharShow
  | StringLess
  | StringToChars
  | CharsToString
  | HandleStdin nominal
  | HandleStdout nominal
  | HandleStderr nominal
  | HandleRead nominal
  | HandleWrite nominal
  | HandleOpenFile nominal nominal
  | HandleClose nominal
  | VecFromList nominal
  | VecToList nominal
  | VecLength nominal
  | ByteFromInt nominal
  | ByteToInt nominal
  | RefNew nominal
  | RefRead nominal
  | RefModify nominal
  | Throw nominal
  | Catch nominal
  | IntNegate
  | FloatNegate
  | MatchFailure
  deriving (Eq, Ord, Show, Functor, Foldable, Traversable)

-- Nominal builtin dependencies include opaque types and marker traits.
data BuiltinType = HandleBuiltin | ByteBuiltin | VecBuiltin | RefBuiltin | ExceptionBuiltin | IOModeBuiltin deriving (Eq, Ord, Show)

builtinTypes :: [BuiltinType]
