-- Authored expectations are read as data and never regenerated by the runner.
data Expectation = Expectation Text [Int] deriving (Show)

instance FromJSON Expectation where
  parseJSON = withObject "expectation" $ \o -> Expectation <$> o .: "kind" <*> o .: "span"

tests :: IO TestTree
tests = do
  let root = "test/fixtures/parsing"
  expected <- eitherDecodeFileStrict' (root </> "expectations.json")
  expectations <- either (ioError . userError) pure expected
  positives <- fixtureFiles (root </> "positive")
  negatives <- fixtureFiles (root </> "negative")
  semanticSources <-
    concat
      <$> mapM
        (\dir -> map (dir </>) <$> fixtureFiles dir)
        [ "test/fixtures/semantics/name-resolution/negative",
          "test/fixtures/semantics/type-checking/negative",
          "test/fixtures/semantics/type-checking/positive"
        ]
  let actualNegatives = map ("negative" </>) negatives
  pure $
    testGroup
      "Ficus parser"
      [ testGroup "positive fixtures" [acceptFixture (root </> "positive" </> f) | f <- positives],
        testCase "negative inventory matches manifest" $
          Set.fromList actualNegatives @?= Set.fromList (Map.keys expectations),
        testGroup
          "negative fixtures"
          [rejectFixture (root </> path) e | (path, e) <- Map.toList expectations],
        testGroup "semantic errors remain parseable" (map acceptFixture semanticSources),
        acceptFixture "test/fixtures/support/Prelude.ficus",
        structuralTests,
        Pretty.tests,
        testGroup
          "lossless source properties"
          [ testProperty "parse/render/parse preserves Concrete tree" roundTrip,
            testProperty "lossless rendering is idempotent" renderIdempotent,
            testProperty "pretty-print/parse preserves syntax" (\(Source source) -> Pretty.roundTrip source),
            testProperty "pretty printing is idempotent" (\(Source source) -> Pretty.idempotent source)
          ]
      ]

fixtureFiles :: FilePath -> IO [FilePath]
fixtureFiles path = sort . filter ((== ".ficus") . takeExtension) <$> listDirectory path

acceptFixture :: FilePath -> TestTree
acceptFixture path = testCase path $ do
  source <- T.readFile path
  case parseModule path source of
    Left d -> assertFailure (show d)
    Right m -> do
      validateConcrete m @?= Right ()
      renderSource m @?= source
      parseModule path (renderSource m) @?= Right m
      Pretty.assertRoundTrip m

rejectFixture :: FilePath -> Expectation -> TestTree
rejectFixture path (Expectation expectedKind expectedSpan) = testCase path $ do
  source <- T.readFile path
  case parseModule path source of
    Right _ -> assertFailure "unexpected parser acceptance"
    Left d -> do
      T.pack (show (diagnosticKind d)) @?= expectedKind
      spanCoordinates (primarySpan d) @?= expectedSpan

spanCoordinates :: Span -> [Int]
spanCoordinates s = [line (start s), column (start s), line (end s), column (end s)]

parsed :: Text -> (ConcreteModule -> Assertion) -> Assertion
parsed source check = case parseModule "Test.ficus" source of
  Left d -> assertFailure (show d)
  Right m -> check m

rhs :: ConcreteModule -> [Expr]
rhs m = [e | d <- moduleDeclarations m, FunctionClause _ _ _ e _ <- [concrete d]]

oneRhs :: Text -> (ExprF -> Assertion) -> Assertion
oneRhs source check = parsed source $ \m -> case rhs m of
  [e] -> check (concrete e)
  _ -> assertFailure "expected one function clause"

structuralTests :: TestTree
structuralTests =
  testGroup
    "Concrete structure"
    [ testCase "trailing RHS annotation wraps the full expression and retains spans" $
        parsed "x = 2 + 3 : Int" $ \m -> case rhs m of
          [e] -> do
            spanCoordinates (location e) @?= [1, 5, 1, 15]
            case concrete e of
              Annotated body ty -> do
                spanCoordinates (location body) @?= [1, 5, 1, 9]
                spanCoordinates (location ty) @?= [1, 13, 1, 15]
                case concrete body of OpApp {} -> pure (); other -> assertFailure (show other)
              other -> assertFailure (show other)
          other -> assertFailure (show other),
      testCase "ordinary identifiers stay ordinary" $
        oneRhs "f = (_, Type, True, False)" $ \case
          Product es -> [nameText n | e <- es, Ident n <- [concrete e]] @?= ["_", "Type", "True", "False"]
          other -> assertFailure (show other),
      testCase "generic pragma arguments" $ parsed "{-# FUTURE_2 x Type (++) \"hello\" #-}" $ \m ->
        case modulePragmas m of
          [p] -> case concrete p of
            Pragma n args -> do
              nameText n @?= "FUTURE_2"
              length args @?= 4
          _ -> assertFailure "expected pragma",
      testCase "dotted chains stay unresolved inside application" $
        oneRhs "f x = g A.B.x.field" $ \case
          App _ arg -> case concrete arg of
            Dotted base ns -> case concrete base of
              Ident n -> map nameText (n : ns) @?= ["A", "B", "x", "field"]
              other -> assertFailure (show other)
            other -> assertFailure (show other)
          other -> assertFailure (show other),
      testCase "negation groups after application" $
        oneRhs "f x = -g x" $ \case
          Negate e -> case concrete e of App _ _ -> pure (); other -> assertFailure (show other)
          other -> assertFailure (show other),
      testCase "spelling-based precedence" $
        oneRhs "f = a + b * c" $ \case
          OpApp _ op r -> do
            nameText op @?= "+"
            case concrete r of OpApp _ inner _ -> nameText inner @?= "*"; other -> assertFailure (show other)
          other -> assertFailure (show other),
      testCase "suffix-based associativity" $
        oneRhs "f = a ?: b ?: c" $ \case
          OpApp _ op r -> do
            nameText op @?= "?:"
            case concrete r of OpApp _ inner _ -> nameText inner @?= "?:"; other -> assertFailure (show other)
          other -> assertFailure (show other),
      testCase "if stays distinct and retains explicit delimiters" $
        oneRhs "f = if { _ -> 1 }" $ \case
          If b -> blockDelimiter b @?= Explicit
          other -> assertFailure (show other),
      testCase "layout expression blocks remain distinct" $
        oneRhs "f =\n  1" $ \case
          ExprBlock b -> blockDelimiter b @?= Layout
          other -> assertFailure (show other),
      testCase "inline expression has no block" $
        oneRhs "f = 1" $
          \case Lit (IntegerLiteral "1") -> pure (); other -> assertFailure (show other),
      testCase "comments retain source order" $ parsed "-- before\nf = 1 {- after -}" $ \m ->
        map commentText (moduleComments m) @?= ["-- before", "{- after -}"],
      testCase "static arguments remain separate" $
        oneRhs "f @a (x : a) = g @a x" $ \case
          App f _ -> case concrete f of StaticApp _ [_] -> pure (); other -> assertFailure (show other)
          other -> assertFailure (show other),
      testCase "static arguments include their at marker" $
        oneRhs "f = g @Int" $ \case
          StaticApp _ [arg] -> spanCoordinates (location arg) @?= [1, 7, 1, 10]
          other -> assertFailure (show other),
      testCase "quantifiers retain their written order" $ parsed "f : {a} -> {b : Type} -> a -> b" $ \m ->
        case moduleDeclarations m of
          [d] -> case concrete d of
            TypeSignature _ sig -> case concrete sig of
              SignatureType qs _ -> [nameText n | q <- qs, Quantifier n _ <- [concrete q]] @?= ["a", "b"]
            other -> assertFailure (show other)
          _ -> assertFailure "expected signature",
      testCase "a multiline head does not make an inline RHS a block" $
        oneRhs "f\n  x = x" $ \case
          Ident n -> nameText n @?= "x"
          other -> assertFailure (show other),
      testCase "a multiline lambda does not make its inline body a block" $
        oneRhs "f = (x\n  y -> x)" $ \case
          Paren e -> case concrete e of
            Lam [] [_, _] body -> case concrete body of Ident n -> nameText n @?= "x"; other -> assertFailure (show other)
            other -> assertFailure (show other)
          other -> assertFailure (show other),
      testCase "record suffixes group before surrounding arguments" $
        oneRhs "f = g p with { x = 1 } y" $ \case
          App call _ -> case concrete call of
            App _ argument -> case concrete argument of RecordWith _ _ -> pure (); other -> assertFailure (show other)
            other -> assertFailure (show other)
          other -> assertFailure (show other),
      testCase "the Concrete boundary rejects incorrect provenance" $ parsed "f = 1\n" $ \m ->
        case moduleDeclarations m of
          d : ds -> case validateConcrete (m {moduleDeclarations = d {origin = SourceOrigin (moduleLocation m)} : ds}) of
            Left _ -> pure ()
            Right () -> assertFailure "invalid provenance accepted"
          [] -> assertFailure "expected declaration"
    ]

newtype Source = Source Text deriving (Show)

instance Arbitrary Source where
  arbitrary = Source <$> sized expressionSource
    where
      expressionSource size = do
        e <- term (min 5 size)
        pure ("f x y = " <> e <> "\n")
      term 0 = elements ["x", "y", "123", "1.5", "True", "_", "\"hello {{world}}\"", "[]", "()"]
      term n =
        oneof
          [ term 0,
            (\a -> "(" <> a <> ")") <$> term (n - 1),
            (\a b -> "(" <> a <> ", " <> b <> ")") <$> term (n - 1) <*> term (n - 1),
            (\a b -> "[" <> a <> ", " <> b <> "]") <$> term (n - 1) <*> term (n - 1),
            (\a b -> "(" <> a <> ") + (" <> b <> ")") <$> term (n - 1) <*> term (n - 1),
            (\a -> "if { True -> " <> a <> "; _ -> x }") <$> term (n - 1),
            (\a -> "{ local = " <> a <> "; local }") <$> term (n - 1)
          ]

roundTrip :: Source -> Property
roundTrip (Source source) = case parseModule "Property.ficus" source of
  Left d -> counterexample (show d) False
  Right m -> parseModule "Property.ficus" (renderSource m) === Right m

renderIdempotent :: Source -> Property
renderIdempotent (Source source) = case parseModule "Property.ficus" source of
  Left d -> counterexample (show d) False
  Right m -> case parseModule "Property.ficus" (renderSource m) of
    Left d -> counterexample (show d) False
    Right n -> renderSource n === renderSource m
