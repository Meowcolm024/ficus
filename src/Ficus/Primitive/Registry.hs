allPrimitives :: [Primitive ()]
allPrimitives = map (erasePrimitive . snd) primitiveCatalog

erasePrimitive :: Primitive nominal -> Primitive ()
erasePrimitive = fmap (const ())

primitiveIndex :: Primitive nominal -> Maybe Int
primitiveIndex operation = elemIndex (erasePrimitive operation) allPrimitives

-- Templates are saturated semantic contracts, independent of inference/Core.
data PrimitiveType nominal
  = ScalarType Intrinsic
  | ListTypeOf (PrimitiveType nominal)
  | NominalType nominal [PrimitiveType nominal]
  | FunctionTypeOf (PrimitiveType nominal) (PrimitiveType nominal)
  | TypeParameter
  | SecondTypeParameter
  deriving (Eq, Show, Functor, Foldable, Traversable)

primitiveSignature :: Primitive nominal -> ([PrimitiveType nominal], PrimitiveType nominal)
primitiveSignature primitiveId = case primitiveId of
  IntAdd -> intBinary int
  IntSubtract -> intBinary int
  IntMultiply -> intBinary int
  IntDivide -> intBinary int
  IntRemainder -> intBinary int
  IntEqual -> intBinary bool
  IntLess -> intBinary bool
  IntShow -> ([int], string)
  StringAppend -> ([string, string], string)
  StringEqual -> ([string, string], bool)
  StringLength -> ([string], int)
  IntToFloat -> ([int], float)
  FloatAdd -> floatBinary float
  FloatSubtract -> floatBinary float
  FloatMultiply -> floatBinary float
  FloatDivide -> floatBinary float
  FloatEqual -> floatBinary bool
  FloatLess -> floatBinary bool
  FloatShow -> ([float], string)
  FloatToInt -> ([float], int)
  CharEqual -> ([char, char], bool)
  CharLess -> ([char, char], bool)
  CharShow -> ([char], string)
  StringLess -> ([string, string], bool)
  StringToChars -> ([string], ListTypeOf char)
  CharsToString -> ([ListTypeOf char], string)
  HandleStdin ident -> ([], NominalType ident [])
  HandleStdout ident -> ([], NominalType ident [])
  HandleStderr ident -> ([], NominalType ident [])
  HandleRead ident -> ([NominalType ident [], int], string)
  HandleWrite ident -> ([NominalType ident [], string], ScalarType UnitType)
  HandleOpenFile ident mode -> ([string, NominalType mode []], NominalType ident [])
  HandleClose ident -> ([NominalType ident []], ScalarType UnitType)
  VecFromList ident -> ([ListTypeOf a], vec ident a)
  VecToList ident -> ([vec ident a], ListTypeOf a)
  VecLength ident -> ([vec ident a], int)
  ByteFromInt ident -> ([int], NominalType ident [])
  ByteToInt ident -> ([NominalType ident []], int)
  RefNew ident -> ([a], NominalType ident [a])
  RefRead ident -> ([NominalType ident [a]], a)
  RefModify ident -> ([NominalType ident [a], FunctionTypeOf a a], ScalarType UnitType)
  Throw ident -> ([NominalType ident [a], a], SecondTypeParameter)
  Catch ident -> ([NominalType ident [a], FunctionTypeOf (ScalarType UnitType) SecondTypeParameter, FunctionTypeOf a SecondTypeParameter], SecondTypeParameter)
  IntNegate -> ([int], int)
  FloatNegate -> ([ScalarType FloatType], ScalarType FloatType)
  MatchFailure -> ([string], a)
  where
    int = ScalarType IntType
    bool = ScalarType BoolType
    string = ScalarType StringType
    float = ScalarType FloatType
    char = ScalarType CharType
    a = TypeParameter
    vec ident argument = NominalType ident [argument]
    floatBinary result = ([float, float], result)
    intBinary result = ([int, int], result)

primitiveArity :: Primitive nominal -> Int
primitiveArity = length . fst . primitiveSignature

-- The evidence operand is explicit in Core/Runtime, a predicate in source.
exceptionTrait :: Primitive nominal -> Maybe nominal
exceptionTrait operation = case operation of
  Throw ident -> Just ident
  Catch ident -> Just ident
  _ -> Nothing

-- Source-defined data and constructor associations used by fallible primitives.
builtinDataTypes :: [Text]
builtinDataTypes = ["ARITHMETIC_ERROR", "IO_ERROR", "MATCH_ERROR", "IO_MODE", "SOMEEXCEPTION"]

data PrimitiveError = DivisionByZeroError | InvalidConversionError | IOError | MatchError deriving (Eq, Ord, Show)

primitiveErrors :: [(PrimitiveError, Text, Text, [Intrinsic])]
primitiveErrors =
  [ (DivisionByZeroError, "ARITHMETIC_ERROR", "DIVISION_BY_ZERO", []),
    (InvalidConversionError, "ARITHMETIC_ERROR", "INVALID_CONVERSION", [StringType]),
    (IOError, "IO_ERROR", "IO_FAILURE", [StringType, StringType]),
    (MatchError, "MATCH_ERROR", "MATCH_FAILURE", [StringType])
  ]

requiredErrors :: Primitive nominal -> [PrimitiveError]
requiredErrors operation = case operation of
  IntDivide -> [DivisionByZeroError]
  IntRemainder -> [DivisionByZeroError]
  FloatToInt -> [InvalidConversionError]
  HandleRead _ -> [IOError]
  HandleWrite _ -> [IOError]
  HandleOpenFile _ _ -> [IOError]
  HandleClose _ -> [IOError]
  MatchFailure -> [MatchError]
  _ -> []

-- Source-defined primitive constructors, including file modes and errors.
builtinConstructors :: [(Text, Text, [Intrinsic])]
builtinConstructors = [(key, owner, fields) | (_, owner, key, fields) <- primitiveErrors] ++ [(key, "IO_MODE", []) | (key, _) <- fileModeConstructors]

builtinDataKeys :: [Text]
builtinDataKeys = builtinDataTypes ++ [key | (key, _, _) <- builtinConstructors]

data FileMode = ReadMode | WriteMode | AppendMode | ReadWriteMode deriving (Eq, Ord, Show)

fileModeConstructors :: [(Text, FileMode)]
fileModeConstructors = [("IO_READ_MODE", ReadMode), ("IO_WRITE_MODE", WriteMode), ("IO_APPEND_MODE", AppendMode), ("IO_READ_WRITE_MODE", ReadWriteMode)]

-- Keys identify nominal record members, independently of their source labels.
builtinRecordMembers :: [(Text, Bool)]
builtinRecordMembers = [("SOMEEXCEPTION_ERR", True), ("SOMEEXCEPTION_VALUE", False), ("SOMEEXCEPTION_SHOWERR", False)]
